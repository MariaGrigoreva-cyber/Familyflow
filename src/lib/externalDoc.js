// Открытие внешних юридических документов (условия использования, политика
// конфиденциальности) — одно место на всё приложение.
//
// Зачем понадобилось. Ссылки стояли обычными <a href> без target. В браузере
// это работало, а внутри Android-обёртки (Capacitor) уводило пользователя на
// страницу документа В ТОМ ЖЕ WebView, где живёт приложение: вернуться оттуда
// нечем — системная кнопка «Назад» по умолчанию закрывает приложение, а не
// возвращает на предыдущую страницу. Человек, нажавший «условия использования»
// на экране регистрации, просто выпадал из приложения. Это же проверяют при
// модерации в RuStore: ссылка на политику должна открываться и не запирать.
//
// Сами адреса здесь НЕ объявляются — они приходят из lib/core.js
// (PRIVACY_URL / TERMS_URL), и второго источника правды не появляется.
import { Browser } from '@capacitor/browser';

/**
 * Приложение запущено в нативной обёртке (Android/iOS), а не в браузере.
 * Проверяем через глобальный Capacitor, а не через импорт: в обычном вебе
 * объекта просто нет, и никакой платформенной логики грузить не нужно.
 */
export function isNativeApp() {
  try {
    return !!window.Capacitor?.isNativePlatform?.();
  } catch {
    return false;
  }
}

/**
 * Открыть документ так, чтобы приложение осталось на месте.
 *
 * Нативно — системный браузер поверх приложения (@capacitor/browser): у него
 * есть своя кнопка закрытия, и возврат гарантирован. В вебе — новая вкладка.
 *
 * noopener обязателен: без него открытая страница получает ссылку на window
 * приложения через window.opener.
 */
export async function openExternalDoc(url) {
  if (!url) return;
  if (isNativeApp()) {
    try {
      await Browser.open({ url });
      return;
    } catch (e) {
      // Плагин недоступен (старая обёртка, сбой моста) — пусть лучше откроется
      // хоть как-то, чем ссылка окажется мёртвой.
      console.error('external doc: Browser.open failed, fallback', e?.message);
    }
  }
  window.open(url, '_blank', 'noopener,noreferrer');
}

/**
 * Пропсы для <a>, открывающей документ. Ссылка остаётся настоящей ссылкой —
 * с href, доступной с клавиатуры и через контекстное меню, — но в нативной
 * обёртке переход перехватывается и уходит в системный браузер.
 *
 * @param url         адрес документа (PRIVACY_URL / TERMS_URL из lib/core.js)
 * @param onClick     дополнительный обработчик; нужен там, где ссылка лежит
 *                    внутри <label> и клик по ней не должен переключать чекбокс
 */
export function externalDocLinkProps(url, { onClick } = {}) {
  return {
    href: url,
    target: '_blank',
    rel: 'noopener noreferrer',
    onClick: e => {
      if (onClick) onClick(e);
      if (isNativeApp()) {
        e.preventDefault();
        openExternalDoc(url);
      }
    },
  };
}
